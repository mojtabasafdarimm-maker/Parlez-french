function transcribe(sentence) {
  let s = sentence.replace(/[’']/g, "'");

  // Replace multi-word expressions with placeholders (longest expressions first)
  const sortedPhrases = [...PHRASES].sort((a, b) => b.fr.length - a.fr.length);
  const placeholders = [];
  sortedPhrases.forEach((item, idx) => {
    const escaped = item.fr.replace(/[’']/g, "'").replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&');
    const reg = new RegExp(escaped, 'gi');
    s = s.replace(reg, () => {
      const key = `__PHR_${idx}_${placeholders.length}__`;
      placeholders.push({ key, ph: item.ph });
      return key;
    });
  });

  // Tokenize words, contractions, numbers, punctuation
  const tokens = s.match(/__PHR_\d+_\d+__|[a-zA-ZÀ-ÿ0-9'-]+|[.,!?:;«»]/g) || [];
  const out = [];

  for (let i = 0; i < tokens.length; i++) {
    const tok = tokens[i];

    // Check placeholder
    const phr = placeholders.find(p => p.key === tok);
    if (phr) {
      out.push(phr.ph);
      continue;
    }

    if (/^[.,!?:;«»]$/.test(tok)) {
      continue;
    }

    const lower = tok.toLowerCase();

    // Direct match in dictionary
    if (W[lower]) {
      let pron = W[lower];
      // Check for common liaisons with next word
      const next = tokens[i + 1] ? tokens[i + 1].toLowerCase().replace(/^[jcdlmtns]'/i, '').replace(/^qu'/i, '') : "";
      const nextStartsVowel = /^[aeiouyhéèêëàâîïôûù]/.test(next);

      if (nextStartsVowel) {
        if (["les", "des", "mes", "tes", "ses", "nos", "vos", "leurs", "ils", "elles", "nous", "vous", "deux", "trois", "six", "dix"].includes(lower)) {
          if (lower === "dix") pron = "deez";
          else if (lower === "six") pron = "seez";
          else if (lower === "deux") pron = "duh-z";
          else if (lower === "trois") pron = "trwah-z";
          else pron = pron + "-z";
        } else if (lower === "un") {
          pron = "uhn-n";
        } else if (lower === "en") {
          pron = "ahn-n";
        } else if (lower === "on") {
          pron = "ohn-n";
        } else if (lower === "est") {
          pron = "ay-t";
        } else if (lower === "sont") {
          pron = "sohn-t";
        } else if (lower === "ont") {
          pron = "ohn-t";
        } else if (lower === "tout") {
          pron = "too-t";
        } else if (lower === "très") {
          pron = "treh-z";
        } else if (lower === "comment") {
          pron = "koh-mahn-t";
        }
      }
      out.push(pron);
    } else {
      // Split contraction if any like d'hiver, l'eau, j'ai, m'habille, etc.
      if (lower.startsWith("j'") || lower.startsWith("c'") || lower.startsWith("d'") || lower.startsWith("l'") || lower.startsWith("m'") || lower.startsWith("t'") || lower.startsWith("s'") || lower.startsWith("n'") || lower.startsWith("qu'")) {
        const prefix = lower.match(/^[a-z]+'/)[0];
        const rest = lower.slice(prefix.length);
        const restPron = W[rest] || rest;
        let blended = "";
        if (prefix === "j'") {
          blended = "zh" + (restPron.startsWith("ay") || restPron.startsWith("ah") || restPron.startsWith("oh") || restPron.startsWith("oo") || restPron.startsWith("uh") || restPron.startsWith("ee") ? restPron : " " + restPron);
        } else if (prefix === "c'") {
          blended = "s" + (restPron.startsWith("ay") || restPron.startsWith("ah") || restPron.startsWith("oh") || restPron.startsWith("oo") || restPron.startsWith("uh") || restPron.startsWith("ee") ? restPron : " " + restPron);
        } else if (prefix === "m'") {
          blended = "m" + restPron;
        } else if (prefix === "t'") {
          blended = "t" + restPron;
        } else if (prefix === "s'") {
          blended = "s" + restPron;
        } else if (prefix === "l'") {
          blended = "l" + restPron;
        } else if (prefix === "d'") {
          blended = "d" + restPron;
        } else if (prefix === "n'") {
          blended = "n" + restPron;
        } else if (prefix === "qu'") {
          blended = "k" + (restPron.startsWith("ee") || restPron.startsWith("el") ? restPron : " " + restPron);
        }
        out.push(blended.trim());
      } else {
        out.push(lower);
      }
    }
  }

  // Format cleanly inside brackets
  const formatted = out.join(" ")
    .replace(/\s+/g, " ")
    .replace(/-\s+/g, "-")
    .replace(/\s+-/g, "-")
    .trim();

  return `[${formatted}]`;
}

